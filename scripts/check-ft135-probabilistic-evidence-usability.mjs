import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const tsx = read('src/pages/ProbabilisticForecastingPage.tsx');
const css = read('src/pages/ProbabilisticForecastingPage.css');
let n=0;
const assert = (test, label) => { if (!test) { console.error('FAIL:', label); process.exitCode=1; } else { n++; console.log('PASS:',label); } };
assert(css.includes('.forecast-table {') && css.includes('width: max(100%, 1020px);'), 'evidence table has minimum readable width');
assert(css.includes('.table-wrap {') && /\.table-wrap\s*\{[^}]*overflow: auto;/s.test(css), 'wide grids can scroll in their container');
assert(css.includes('overflow-wrap: normal;') && css.includes('word-break: normal;'), 'ordinary business words are not broken arbitrarily');
assert(css.includes('min-width: 152px;'), 'first business column has adequate minimum width');
assert(css.includes('min-width: 72px;'), 'heading has minimum width');
assert(tsx.includes('<details className="forecast-technical-reference">'), 'raw calibration key is hidden behind disclosure');
assert(tsx.includes("<summary>{ui('Technical details')}</summary>"), 'disclosure explains technical reference');
assert(tsx.includes('<code>{observation.calibration_key}</code>'), 'full original key remains accessible');
assert(!tsx.includes('<span className="forecast-table__subtext">{observation.calibration_key}</span>'), 'raw long ID is not permanently shown in business table');
assert(tsx.includes('canViewDiagnostics && observation.calibration_key'), 'existing diagnostics permission gate retained');
assert(tsx.includes('formatNumber(observation.predicted_value, locale)') && tsx.includes('formatNumber(observation.actual_value, locale)'), 'forecast numeric business data unchanged');
assert(tsx.includes('formatAssessmentBoolean(observation.interval_captured_actual, ui)'), 'calibration flags unchanged');
console.log(`${n}/12 checks passed`);
