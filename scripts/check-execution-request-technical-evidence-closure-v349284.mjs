import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const src = fs.readFileSync(path.join(root, 'src/pages/ExecutionRequestsPage.tsx'), 'utf8');
const active = src.replace(/\{\/\*[\s\S]*?\*\/\}/g, '').replace(/\/\*[\s\S]*?\*\//g, '');
let failed = false;
const check = (name, ok) => { console.log(`${ok ? 'PASS' : 'FAIL'}: ${name}`); if (!ok) failed = true; };
check('technical security disclosure removed', !active.includes("Technical security evidence"));
check('technical audit disclosure removed', !active.includes("Technical audit evidence"));
check('security raw JSON renderer removed', !active.includes('<JsonBlock value={securityAudit} />'));
check('audit raw JSON renderer removed', !active.includes('<JsonBlock value={auditPack} />'));
check('generic JSON helper removed from live page', !active.includes('function JsonBlock('));
check('security review retained', active.includes("ui('Security review')"));
check('security checks retained', active.includes("ui('Checks')") && active.includes('securityAudit.checks.map'));
check('audit pack retained', active.includes("ui('Audit pack')"));
check('audit completeness retained', active.includes("ui('Audit events')") && active.includes("ui('Complete')"));
check('human-readable audit trail retained', active.includes("ui('Audit trail')") && active.includes('auditPack.audit_trail.map'));
check('security API loading retained', active.includes('/security-audit'));
check('audit-pack API loading retained', active.includes('/audit-pack'));
check('advanced technical snapshots remain hidden/commented', src.includes("Technical snapshots are intentionally hidden from all tenant users.") && !active.includes("Technical snapshots (advanced)"));
if (failed) process.exit(1);
