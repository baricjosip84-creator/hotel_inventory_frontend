/* FT031: executable hash-routing regression and source guard checks. */
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = join(__dirname,'..');
const code = readFileSync(join(root,'src/layouts/scrollToRouteAnchor.ts'),'utf8');
const js = ts.transpileModule(code,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod = {exports:{}};
vm.runInNewContext(js,{module:mod,exports:mod.exports,decodeURIComponent}, {filename:'scrollToRouteAnchor.js'});
const fn = mod.exports.scrollToRouteAnchor;
let calls=[];
const findTarget = (id) => id === 'usage-damage-waste-review' ? {scrollIntoView(opts){ calls.push({id,block:opts.block,behavior:opts.behavior}); }} : null;
assert.equal(fn('#usage-damage-waste-review',findTarget),true);
assert.equal(calls.length,1);
assert.equal(calls[0].id,'usage-damage-waste-review');
assert.equal(calls[0].block,'start');
assert.equal(calls[0].behavior,'auto');
assert.equal(fn('',findTarget),false);
assert.equal(fn('#missing-target',findTarget),false);
assert.equal(fn('#%E0%A4%A',findTarget),false);
assert.equal(calls.length,1,'no scrolling for invalid/unknown hashes');
const layout=readFileSync(join(root,'src/layouts/AppLayout.tsx'),'utf8');
assert.match(layout,/if \(!scrollToRouteAnchor\(location\.hash\)\) forcePageScrollTop\(\)/);
assert.match(layout,/\[location\.pathname, location\.hash\]/);
for(const delay of ['0','50','150','350']) assert.ok(layout.includes(`window.setTimeout(placeScroll, ${delay})`));
const alerts=readFileSync(join(root,'src/pages/AlertsPage.tsx'),'utf8');
const usage=readFileSync(join(root,'src/pages/inventoryUsage/InventoryUsageDashboard.tsx'),'utf8');
assert.ok(alerts.includes("'/inventory-usage#usage-damage-waste-review'"));
assert.ok(usage.includes('id="usage-damage-waste-review"'));
console.log('FT031 route anchor regression PASS (11 checks including timed restore prevention)');
