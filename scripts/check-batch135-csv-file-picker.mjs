import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const code=read('src/components/imports/InventoryCsvImportPanel.tsx');
const catalog=read('src/i18n/tenantUiTranslations.ts');
const storage=read('src/pages/StorageLocationsPage.tsx');
const suppliers=read('src/pages/SuppliersPage.tsx');
const enterprise=read('src/components/enterpriseInventory/EnterpriseFilePicker.tsx');
const api=read('src/components/imports/inventoryCsvImport.ts');
let checks=0;
const assert=(ok,label)=>{checks++;if(!ok)throw Error(`FAIL ${checks}: ${label}`);};
const src=ts.createSourceFile('InventoryCsvImportPanel.tsx',code,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
assert(src.parseDiagnostics.length===0,'CSV panel valid TSX syntax');
const attr=(el,name)=>el.attributes?.properties?.find(x=>ts.isJsxAttribute(x)&&x.name.text===name);
const jsxAttrs=(tag)=>{let found=[];function walk(n){if(ts.isJsxSelfClosingElement(n)&&n.tagName.getText(src)===tag)found.push(n);if(ts.isJsxOpeningElement(n)&&n.tagName.getText(src)===tag)found.push(n);ts.forEachChild(n,walk);}walk(src);return found;};
const inputs=jsxAttrs('input');
const native=inputs.find(n=>attr(n,'type')?.initializer?.text==='file');
assert(native,'native file input retained');
assert(attr(native,'accept')?.initializer?.text==='.csv,text/csv','CSV/MIME accept filter unchanged');
assert(attr(native,'ref')?.getText(src).includes('fileInputRef'),'the same file input ref is preserved');
assert(attr(native,'onChange')?.getText(src).includes('handleFile'),'the existing file parsing/change handler is preserved');
const restriction='!canImport || busy || batch?.status === \'committed\'';
assert(attr(native,'disabled')?.getText(src).includes(restriction),'native input permission/pending/committed guard remains');
assert(attr(native,'tabIndex')?.getText(src)==='tabIndex={-1}','hidden input removed from tab sequence');
assert(attr(native,'aria-hidden')?.getText(src)==='aria-hidden="true"','hidden native control not double-announced');
assert(attr(native,'style')?.getText(src).includes("display: 'none'"),'native chooser chrome hidden');
const buttons=jsxAttrs('button');
const trigger=buttons.find(n=>attr(n,'onClick')?.getText(src).includes('fileInputRef.current?.click()'));
assert(trigger,'visible trigger opens actual browser file chooser');
assert(attr(trigger,'type')?.initializer?.text==='button','file picker does not submit the import form');
assert(attr(trigger,'disabled')?.getText(src).includes(restriction),'button has same permissions/loading/commit disabled guard');
assert(attr(trigger,'style')?.getText(src).includes('disabledButton : button'),'button uses normal app button and disabled style');
assert(attr(trigger,'data-skip-global-action-feedback')?.initializer?.text==='true','opening file dialog never claims import success');
assert(code.includes("{ui('Choose file')}"),'visible action uses translated Choose file label');
const announcer=jsxAttrs('span').find(n=>attr(n,'aria-live')?.initializer?.text==='polite');
assert(announcer,'file selection status announced politely');
assert(attr(announcer,'role')?.initializer?.text==='status','selected filename has status semantics');
assert(code.includes("{file ? file.name : ui('No file selected')}"),'real selected filename displayed with translated empty state');
assert(code.includes("title={file?.name || undefined}"),'long file name accessible via title');
assert(code.includes("overflowWrap: 'anywhere'"),'long filenames do not overflow narrow layouts');
// Extract and actually execute the real onClick arrow with an inert ref mock.
const clickAttribute=attr(trigger,'onClick');
const expression=clickAttribute.initializer.expression;
const transpiled=ts.transpileModule(`const click = ${expression.getText(src)}; click();`,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext}}).outputText;
let count=0;
vm.runInNewContext(transpiled,{fileInputRef:{current:{click(){count++;}}}});
assert(count===1,'visible trigger calls the real native input exactly once');
vm.runInNewContext(transpiled,{fileInputRef:{current:null}});
assert(count===1,'missing input ref does not crash or invent a click');
assert(code.includes('setFile(selected);') && code.includes('setRows([]);'),'existing file/CSV selection and reset behavior preserved');
assert(code.includes('parseCsv(await selected.text())'),'existing CSV parser and selected File.text preserved');
assert(code.includes("endsWith('.csv')"),'CSV extension guard maintained');
assert(code.includes('if (parsed.length > 2000)'),'2,000-row cap maintained');
assert(code.includes("setMessageTone(preview.status === 'validated' ? 'success' : 'warning');"),'invalid preview remains warning, not successful import');
assert(code.includes("batch.status !== 'validated'"),'commit still blocks unvalidated imports');
assert(code.includes('fileInputRef.current.value = \'\''),'start over clears native file input');
assert(code.includes("onInteraction?.();\n    resetPreview();"),'file selection retains stale-feedback cleanup');
assert(api.includes('skipMutationFeedback: true'),'read-only preview suppresses global success toast');
assert(storage.includes('<InventoryCsvImportPanel')&&suppliers.includes('<InventoryCsvImportPanel'),'shared fix covers both audited Storage Locations and Suppliers imports');
assert(enterprise.includes("{ui('Choose file')}"),'existing enterprise control uses the same label');
for(const name of ['Choose file','No file selected']){
 const row=catalog.split('\n').find(line=>line.trim().startsWith('["'+name+'",'));
 assert(row,'five-language catalog contains '+name);
 const fields=JSON.parse(row.trim().replace(/,$/,''));
 assert(fields.length===5&&fields.every(x=>x.length>0),'five nonempty localizations for '+name);
}
assert(!code.includes('fetch(')&&code.includes('commitInventoryImport(batch)'),'picker does not add new API calls or bypass existing commit boundary');
console.log(`Batch135 CSV file picker guard PASS (${checks}/${checks})`);
