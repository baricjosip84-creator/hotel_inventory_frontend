import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = process.cwd();
const pagePath = path.join(root,'src/pages/AlertsPage.tsx');
const helperPath = path.join(root,'src/lib/alertQueueIntegrity.ts');
const translationPath = path.join(root,'src/i18n/tenantUiTranslations.ts');
const page=fs.readFileSync(pagePath,'utf8');
const helper=fs.readFileSync(helperPath,'utf8');
const translation=fs.readFileSync(translationPath,'utf8');
let checks=0;
function check(condition,message){assert.ok(condition,message);checks++;}
for(const [file,source,kind] of [[pagePath,page,ts.ScriptKind.TSX],[helperPath,helper,ts.ScriptKind.TS],[translationPath,translation,ts.ScriptKind.TS]]){
  const ast=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true,kind);
  check(ast.parseDiagnostics.length===0,`${path.basename(file)} valid TypeScript syntax`);
}
const code=ts.transpileModule(helper,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {mergeFocusedAlert,summarizeFilteredAlerts,isFocusedAlertOutsideFilters,formatNullableAlertQuantity}=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(code));
const active={id:'A',resolved:false,severity:'critical',acknowledged:false};
const resolved={id:'B',resolved:true,severity:'info',acknowledged:true};
const outside={id:'C',resolved:false,severity:'warning',acknowledged:false};
const filtered=[active,resolved];
const originalSnapshot=JSON.stringify(filtered);
check(mergeFocusedAlert(filtered,null).length===2,'no focus keeps queue');
check(mergeFocusedAlert(filtered,active).length===2,'focused existing row not duplicated');
check(mergeFocusedAlert(filtered,active)[0].id==='A','focused existing row first');
check(mergeFocusedAlert(filtered,resolved)[0].id==='B','focused existing row moves first');
check(mergeFocusedAlert(filtered,outside).length===3,'external link is shown');
check(mergeFocusedAlert(filtered,outside)[0].id==='C','external linked alert first');
check(mergeFocusedAlert(filtered,outside).filter(x=>x.id==='C').length===1,'external linked alert not duplicated');
check(JSON.stringify(filtered)===originalSnapshot,'merge leaves React Query array unchanged');
check(isFocusedAlertOutsideFilters(filtered,outside),'outside linked alert labelled');
check(!isFocusedAlertOutsideFilters(filtered,active),'in-filter linked alert not labelled outside');
check(!isFocusedAlertOutsideFilters(filtered,null),'null focus not outside');
const counts=summarizeFilteredAlerts(filtered);
check(counts.total===2,'total excludes external pinned alert');
check(counts.unresolved===1,'open count excludes external pinned alert');
check(counts.critical===1,'critical count');
check(counts.unacknowledged===1,'unacknowledged count');
check(summarizeFilteredAlerts([]).total===0,'empty queue total');
check(summarizeFilteredAlerts([]).critical===0,'empty critical count');
const countsWithOutside=summarizeFilteredAlerts(mergeFocusedAlert(filtered,outside));
check(countsWithOutside.total===3 && counts.total===2,'including pin would inflate total (regression proof)');
check(countsWithOutside.unresolved===2 && counts.unresolved===1,'including pin would inflate open count');
const fmt=(value)=>`#${value}`;
check(formatNullableAlertQuantity(null,'kg',fmt)==='—','null is missing');
check(formatNullableAlertQuantity(undefined,'kg',fmt)==='—','undefined is missing');
check(formatNullableAlertQuantity('','kg',fmt)==='—','empty string is missing');
check(formatNullableAlertQuantity('  ','kg',fmt)==='—','whitespace is missing');
check(formatNullableAlertQuantity('bad','kg',fmt)==='—','nonnumeric is missing');
check(formatNullableAlertQuantity('Infinity','kg',fmt)==='—','infinite is missing');
check(formatNullableAlertQuantity(0,'kg',fmt)==='#0 kg','real zero is retained');
check(formatNullableAlertQuantity('0','pcs',fmt)==='#0 pcs','string zero retained');
check(formatNullableAlertQuantity('1.25','kg',fmt)==='#1.25 kg','decimal retained');
check(formatNullableAlertQuantity(-2,null,fmt)==='#-2','negative signed values retained');
check(page.includes('const summary = useMemo(() => summarizeFilteredAlerts(filteredAlerts), [filteredAlerts]);'),'page summarizes filtered queue');
check(page.includes('mergeFocusedAlert(filteredAlerts, focusedAlertQuery.data)'),'page merges focused alert without mutating query');
check(page.includes('isFocusedAlertOutsideFilters(filteredAlerts, focusedAlertQuery.data)'),'page detects pinned external alert');
check(page.includes('focusedOutsideFilters ? ('),'page makes external pin visible');
check(page.includes('focusedAlertQuery.isError && !requestedAlertIsRendered ? ('),'page surfaces an error only if focused alert is absent from the visible queue');
check(page.includes('formatNullableAlertQuantity(value, unit,'),'page does not turn missing stock into zero');
for(const label of ['Linked alert could not be loaded.','The linked alert is shown separately and is not included in the filtered totals.']){
 const start=translation.indexOf(`  ["${label}"`);
 check(start!==-1,`translated label ${label}`);
 const line=translation.substring(start,translation.indexOf('\n',start)).trim();
 check(JSON.parse(line.slice(0,-1)).length===5,`five locales for ${label}`);
}
console.log(`PASS ${checks}/${checks} alert-queue focused-record totals, unknown stock evidence and missing-link regression checks`);
