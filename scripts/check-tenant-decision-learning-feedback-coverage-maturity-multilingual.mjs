import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const fail = (message) => { console.error(`FAIL: ${message}`); process.exitCode = 1; };
const pass = (message) => console.log(`PASS: ${message}`);

const translationSource = read('src/i18n/tenantUiTranslations.ts');
const pageSource = read('src/pages/DecisionLearningFeedbackPage.tsx');
const routerSource = read('src/app/router.tsx');

const rows = [];
for (const line of translationSource.split(/\r?\n/)) {
  const trimmed = line.trim();
  if (!trimmed.startsWith('[') || !trimmed.endsWith(',')) continue;
  try {
    const row = JSON.parse(trimmed.slice(0, -1));
    if (Array.isArray(row) && row.length === 5 && row.every((item) => typeof item === 'string')) rows.push(row);
  } catch {}
}
const keys = rows.map((row) => row[0]);
const unique = new Set(keys);
if (keys.length !== unique.size) fail('Tenant UI translation catalog contains duplicate English keys.');
else pass(`Tenant UI catalog has ${keys.length} unique five-language rows.`);

for (const required of [
  "import { useAppTranslation } from '../i18n/I18nContext';",
  "import { formatLocalizedNumber } from '../i18n/formatters';"
]) if (!pageSource.includes(required)) fail(`Decision Learning Feedback multilingual wiring missing: ${required}`);
if (!process.exitCode) pass('Coverage/maturity slice uses the shared tenant translation and locale runtime.');

const literalPattern = /\bui\(\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')\s*\)/g;
function decode(literal) {
  if (literal.startsWith('"')) return JSON.parse(literal);
  const body = literal.slice(1, -1).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return JSON.parse(`"${body}"`);
}
const literals = [];
for (const match of pageSource.matchAll(literalPattern)) { try { literals.push(decode(match[1])); } catch {} }
const missing = [...new Set(literals.filter((key) => !unique.has(key)))];
if (missing.length) fail(`Decision Learning Feedback ui() literals missing translations: ${missing.join(' | ')}`);
else pass(`Decision Learning Feedback currently has ${new Set(literals).size} catalog-backed literal UI keys.`);

const dynamicPresentationKeys = [
  'no feedback coverage yet',
  'coverage gap attention required',
  'coverage present with review pressure',
  'coverage controlled',
  'no roadmap loaded',
  'closed loop maturity blocked by governance or evidence gaps',
  'ready for manual closed loop governance review',
  'closed loop maturity in progress',
  'capture feedback evidence',
  'evidence capture',
  'not started',
  'in progress',
  'coverage gap',
  'resolve review pressure',
  'human review governance',
  'review required',
  'controlled',
  'calibrate decision logic',
  'manual recalibration readiness',
  'recalibration review required',
  'stable',
  'prepare closed loop learning',
  'closed loop readiness',
  'ready for manual closed loop review',
  'not ready for closed loop escalation'
];
const missingDynamic = dynamicPresentationKeys.filter((key) => !unique.has(key));
if (missingDynamic.length) fail(`Coverage/maturity dynamic display keys missing translations: ${missingDynamic.join(' | ')}`);
else pass(`${dynamicPresentationKeys.length} coverage/maturity canonical display values are catalog-backed.`);

for (const required of [
  "{ui('Learning coverage matrix')}",
  "{ui('Backend-generated domain coverage view showing where feedback evidence exists and which evidence types are still missing. This is gap visibility only; it does not train models or update policies.')}",
  '<LocalizedLearningStatCard label="Coverage posture"',
  '<LocalizedLearningStatCard label="Average coverage"',
  "<th>{ui('Next capture')}</th>",
  'formatLocalizedNumber(row.coverage_score ?? 0, locale)',
  'formatLocalizedNumber(row.review_pressure_count ?? 0, locale)',
  "{ui('No coverage rows available yet.')}",
  "{ui('Learning maturity roadmap')}",
  "{ui('Manual closed-loop readiness view generated by the backend. It shows what must mature before learning evidence can safely inform future tuning; it does not train models, update policies, or execute changes.')}",
  '<LocalizedLearningStatCard label="Roadmap posture"',
  "label={ui('Next maturity focus')}",
  "{ui('Blockers:')}",
  "<th>{ui('Recommended next step')}</th>",
  'ui(formatLabel(phase.phase_key))',
  'ui(formatLabel(phase.maturity_layer))',
  'formatLocalizedNumber(phase.readiness_score ?? 0, locale)',
  'ui(formatLabel(phase.status))',
  "{ui('No maturity phases available yet.')}"
]) if (!pageSource.includes(required)) fail(`Localized coverage/maturity presentation missing: ${required}`);
if (!process.exitCode) pass('Learning coverage matrix and Learning maturity roadmap presentation use the multilingual contract.');

const sliceStart = pageSource.indexOf('function LearningCoverageMatrix(');
const sliceEnd = pageSource.indexOf('function ClosedLoopExceptionRegister(');
if (sliceStart < 0 || sliceEnd <= sliceStart) fail('Unable to isolate the staged coverage/maturity slice.');
else {
  const slice = pageSource.slice(sliceStart, sliceEnd);
  const rawText = slice.split(/\r?\n/).flatMap((line) => {
    const match = line.match(/>\s*([A-Za-z][^<>{}]*)\s*</);
    return match ? [match[1].trim()] : [];
  }).filter(Boolean);
  if (rawText.length) fail(`Raw JSX presentation remains in coverage/maturity slice: ${rawText.join(' | ')}`);
  else pass('Coverage/maturity slice has no remaining raw JSX presentation text.');
}

for (const required of [
  '<td>{formatLabel(row.domain)}</td>',
  '<td>{formatLabel(row.recommended_next_capture)}</td>',
  "<td>{(row.missing_evidence_types || []).map(formatLabel).join(', ') || '—'}</td>",
  "value={formatLabel(roadmap?.next_maturity_focus || 'maintain_manual_closed_loop_readiness_review')}",
  "{(roadmap?.blockers || []).map(formatLabel).join(', ')}",
  '<td>{formatLabel(phase.recommended_next_step)}</td>'
]) if (!pageSource.includes(required)) fail(`Expected backend-data boundary missing: ${required}`);
for (const forbidden of [
  'ui(formatLabel(row.domain))',
  'ui(formatLabel(row.recommended_next_capture))',
  'ui(formatLabel(roadmap?.next_maturity_focus',
  'ui(formatLabel(phase.recommended_next_step))'
]) if (pageSource.includes(forbidden)) fail(`Backend domain/blocker/recommendation data must remain raw: ${forbidden}`);
if (!process.exitCode) pass('Backend domain, gap, blocker and recommendation data remain raw while known canonical presentation states are localized.');

if (!pageSource.includes("ui('The latest saved records in this category.')")) fail('Completed-page sentinel must confirm the EvidenceTable saved-records description is localized.');
else pass('Decision Learning Feedback staged boundary is complete through the final EvidenceTable presentation.');

for (const required of [
  "path: 'decision-learning-feedback'",
  'TENANT_PERMISSIONS.DECISION_INTELLIGENCE_READ',
  '<DecisionLearningFeedbackPage />'
]) if (!routerSource.includes(required)) fail(`Decision Learning Feedback router/permission contract changed: ${required}`);
if (!process.exitCode) pass('Decision Learning Feedback route and DECISION_INTELLIGENCE_READ permission contract remain unchanged.');

for (const required of [
  "apiRequest<ContinuousLearningSummary>('/decision-intelligence/continuous-learning-summary?limit=25')",
  "apiRequest<Record<string, unknown>>(`/decision-intelligence-feedback/${mode}`, {",
  "method: 'POST'"
]) if (!pageSource.includes(required)) fail(`Existing Decision Learning Feedback request contract missing: ${required}`);
if (!process.exitCode) pass('Existing summary read and governed feedback-evidence POST contracts remain unchanged.');

if (!process.exitCode) pass('Tenant Decision Learning Feedback Coverage & Maturity multilingual gate passed.');
