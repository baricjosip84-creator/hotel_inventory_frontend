import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = process.cwd();
const read = (rel) => fs.readFileSync(path.join(root, rel),'utf8');
const app = read('src/app/AppProviders.tsx');
const api = read('src/lib/api.ts');
const events = read('src/lib/actionFeedback.ts');
const users = read('src/pages/UsersPage.tsx');
const i18n = read('src/i18n/tenantUiTranslations.ts');
const pkg = JSON.parse(read('package.json'));
const checks=[];
function check(label, result){ const pass=Boolean(result); checks.push(pass); console.log(`${pass?'PASS':'FAIL'} ${label}`); }
const ast=ts.createSourceFile('AppProviders.tsx',app,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
check('Modified toast component parses as TSX',ast.parseDiagnostics.length===0);
const rendered=ts.transpileModule(app,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
check('Toast TSX transpiles without diagnostics',(rendered.diagnostics||[]).length===0);
const tagName=(node)=>node.tagName?.getText(ast);
const details=[]; const summaries=[]; const smalls=[];
function walk(node){if(ts.isJsxElement(node)){ const name=tagName(node.openingElement); if(name==='details')details.push(node); if(name==='summary')summaries.push(node); if(name==='small')smalls.push(node); } ts.forEachChild(node,walk);}
walk(ast);
check('One native technical disclosure added',details.length>=1);
const toastDisclosure=details.find(node=>node.getText(ast).includes('toastTechnicalDetails'));
check('Toast Request ID is inside native disclosure',toastDisclosure?.getText(ast).includes('item.requestId') && toastDisclosure?.getText(ast).includes('toastRequestId'));
check('Disclosure defaults closed (no open attribute)',toastDisclosure && !toastDisclosure.openingElement.attributes.properties.some(x=>x.name?.getText(ast)==='open'));
check('Native summary present within disclosure',toastDisclosure?.getText(ast).includes('<summary') && summaries.length>=1);
check('Tenant disclosure label translated',toastDisclosure?.getText(ast).includes("ui('Technical details')"));
check('Platform disclosure label stays English',toastDisclosure?.getText(ast).includes(": 'Technical details'"));
check('Technical request ID remains available exactly',toastDisclosure?.getText(ast).includes("ui('Request ID')") && toastDisclosure?.getText(ast).includes('item.requestId'));
check('Empty request ID does not render disclosure',app.includes('{item.requestId ? ('));
check('No full ID outside collapsed native details',!/\{item\.requestId \? <small>/.test(app));
check('Business message still outside technical disclosure',app.indexOf('<span>{message}</span>')<app.indexOf('<details style={styles.toastTechnicalDetails}>'));
check('Dismiss button remains accessible',app.includes('aria-label={tenant ? ui(\'Dismiss message\') : \'Dismiss platform message\'}'));
check('Toast auto-dismiss behavior preserved',app.includes('7500') && app.includes('4500'));
check('Toast dedupe includes request ID unchanged',app.includes("feedbackEvent.detail.requestId || ''"));
check('Full request ID still retained in toast model',app.includes('requestId: feedbackEvent.detail.requestId,'));
check('Native summary has pointer visual indication',app.includes("toastTechnicalSummary: {") && app.includes("cursor: 'pointer'"));
check('Long identifiers wrap in narrow toasts',app.includes("toastRequestId: {") && app.includes("overflowWrap: 'anywhere'"));
check('Tenant technical label has five translations',(i18n.split('\n').find(x=>x.includes('  ["Technical details",'))?.match(/"/g)||[]).length===10);
check('Tenant Request ID label has five translations',(i18n.split('\n').find(x=>x.includes('  ["Request ID",'))?.match(/"/g)||[]).length===10);
check('API event still passes request ID',api.includes('requestId: error instanceof ApiError ? error.requestId : undefined'));
check('Original API failure capture preserved',api.includes('captureApiFailure({'));
check('Public error helper can still supply ID to toast',events.includes('requestId?: string') && events.includes('dispatchFeedback(TENANT_MUTATION_FEEDBACK_EVENT'));
check('Users duplicate-email business message preserved',users.includes("ui('This email is already used by another tenant user.')"));
check('Existing global action safety remains enabled',app.includes('useGlobalButtonActionSafety();'));
check('Npm test entry registered',pkg.scripts?.['check:toast-technical-request-id-v349338']==='node scripts/check-toast-technical-request-id-surgical-fix-v349338.mjs');
console.log(`Batch100 toast technical request ID source guard: ${checks.filter(Boolean).length}/${checks.length} PASS`);
if (checks.some(pass=>!pass)) process.exitCode=1;
