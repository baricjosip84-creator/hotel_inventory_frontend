import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = path.resolve(import.meta.dirname, '..');
const source = (file) => readFileSync(path.join(root, file), 'utf8');
const api = source('src/lib/api.ts');
const page = source('src/pages/InventoryCapabilitiesPage.tsx');
const style = source('src/pages/InventoryCapabilitiesPage.css');
const translations = source('src/i18n/tenantUiTranslations.ts');
const backend = readFileSync(path.resolve(root,'../backend/src/services/inventory/inventoryCapabilitiesService.js'), 'utf8');
const pkg = JSON.parse(source('package.json'));
let count = 0;
const check = (label, fn) => { fn(); console.log(`PASS ${String(++count).padStart(2,'0')} ${label}`); };
const apiTree = ts.createSourceFile('api.ts', api, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const pageTree = ts.createSourceFile('page.tsx', page, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
check('Both changed TS sources parse', () => {
  assert.equal(apiTree.parseDiagnostics.length, 0);
  assert.equal(pageTree.parseDiagnostics.length, 0);
});
check('API transpilation is error-free', () => assert.equal(ts.transpileModule(api,{fileName:'api.ts',reportDiagnostics:true,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).diagnostics.filter(x=>x.category===ts.DiagnosticCategory.Error).length,0));
check('LandedCostPanel preserved', () => assert.match(page,/function LandedCostPanel\(/));
const start = page.indexOf('function LandedCostPanel(');
const end = page.indexOf('function suggestVariantSku(', start);
assert.ok(start >= 0 && end > start);
const panel = page.slice(start,end);
const button = panel.match(/<button className="button capability-cost-finalize"[^>]+>.*?<\/button>/)?.[0];
check('Finalize has disabled and locked visual state',()=>{ assert.ok(button); assert.match(button,/disabled=\{!canWrite \|\| !shipmentId \|\| selectedShipment\?\.status !== 'received' \|\| total <= 0 \|\| !preview \|\| previewMutation\.isPending \|\| finalizeMutation\.isPending\}/); assert.match(button,/ui\("Locked"\)/); });
check('Safe preview still permitted while shipment partial',()=>assert.match(panel,/disabled=\{!shipmentId \|\| total <= 0 \|\| previewMutation\.isPending \|\| finalizeMutation\.isPending\} onClick=\{\(\) => previewMutation\.mutate\(\)\}/));
check('Guard warning linked to button accessibly',()=>{
  assert.match(button,/aria-describedby=\{shipmentId && selectedShipment\?\.status !== 'received' \? "landed-cost-finalization-guard" : undefined\}/);
  assert.match(panel,/id="landed-cost-finalization-guard"[^>]+role="status"/);
});
check('Visual disabled style strong enough to override general hover',()=>{
  assert.match(style,/\.io-advanced-inventory-page \.capability-cost-finalize:disabled:hover/);
  assert.match(style,/background: #e2e8f0/);
  assert.match(style,/cursor: not-allowed/);
});
check('Actual button path remains the original guarded mutation',()=>assert.match(button,/onClick=\{\(\) => finalizeMutation\.mutate\(\)\}/));
check('Changing inputs still invalidates old previews',()=>assert.match(panel,/const changePreviewInput = \(change: \(\) => void\) => \{ change\(\); setPreview\(null\); setError\(null\); \};/));
check('Finalization still submits fingerprint',()=>assert.match(panel,/preview_fingerprint: preview\?\.preview_fingerprint/));
check('Original backend rejects partial finalization',()=>assert.match(backend,/if \(preview\.shipment\.status !== 'received'\) \{\s*throw new AppError\(409, 'LANDED_COST_SHIPMENT_NOT_RECEIVED'/));
check('Original backend checks fingerprint before finalization',()=>assert.match(backend,/if \(!reviewedFingerprint \|\| reviewedFingerprint !== preview\.preview_fingerprint\)/));
check('Original backend refuses duplicate finalized records',()=>assert.match(backend,/if \(existing\.rows\.length\) throw new AppError\(409, 'LANDED_COST_ALREADY_FINALIZED'/));
const required=['isProductPackageMutationPath','readMutationStringField','readMutationBooleanField','readMutationNumberField','readMutationAction','barcodeLabelCreatedMessage','tenantMutationActionLabel','tenantMutationSuccessMessage'];
const found={};
function visit(n) { if (ts.isFunctionDeclaration(n) && required.includes(n.name?.text)) found[n.name.text]=n; ts.forEachChild(n, visit); }
visit(apiTree);
check('API feedback function extracted from actual TS AST',()=>assert.ok(required.every(n=>found[n])));
const body=required.map(n=>found[n].getText(apiTree)).join('\n');
const js=ts.transpileModule(body,{fileName:'ft174.ts',compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const getMessage = new Function(js+'\nreturn tenantMutationSuccessMessage;')();
const endpoint='/inventory-capabilities/landed-costs/preview';
const expected='Landed cost preview calculated. No costs were finalized.';
check('Successful preview has precise read-only message',()=>assert.equal(getMessage(endpoint,'POST','{}'),expected));
check('Preview message unaffected by query string and case',()=>{assert.equal(getMessage(endpoint.toUpperCase()+'?a=1','post',null),expected)});
check('Preview GET never receives POST confirmation',()=>assert.notEqual(getMessage(endpoint,'GET','{}'),expected));
check('Preview nested/unrelated POST not overwritten',()=>assert.notEqual(getMessage(endpoint+'/other','POST','{}'),expected));
check('Finalization confirmation still distinct',()=>assert.equal(getMessage('/inventory-capabilities/landed-costs/finalize','POST','{}'),'Landed cost finalized successfully.'));
check('Other inventory mutations still specific',()=>assert.equal(getMessage('/inventory-capabilities/products/p1/uom','POST',JSON.stringify({expected_version:0})),'Unit conversion saved successfully.'));
check('API successful POST actually uses feedback mapper',()=>assert.match(api,/message: tenantMutationSuccessMessage\(path, method, requestOptions\.body\), translateMessage: true/));
const row=translations.split('\n').filter(line=>line.trim().startsWith('["'+expected+'",'));
check('Preview feedback has exactly one localized entry',()=>assert.equal(row.length,1));
const translated = JSON.parse(row[0].trim().replace(/,$/,''));
check('All five translations present',()=>assert.ok(translated.length===5 && translated.every(x=>x && x.length>20)));
check('NPM focused command registered',()=>assert.equal(pkg.scripts['check:ft174-landed-cost-preview-and-finalize-guard'],'node scripts/check-ft174-landed-cost-preview-and-finalize-guard.mjs'));
console.log(`FT174 targeted controls: ${count}/${count} PASS`);
