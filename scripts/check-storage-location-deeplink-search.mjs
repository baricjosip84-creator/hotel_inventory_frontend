import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = process.cwd();
const pageFile = path.join(root, 'src/pages/StorageLocationsPage.tsx');
const utilFile = path.join(root, 'src/lib/storageLocationDirectoryUrl.ts');
const page = fs.readFileSync(pageFile,'utf8');
const utility = fs.readFileSync(utilFile,'utf8');
let checks=0;
function check(value, name){assert.ok(value,name);checks++;}
for(const [file,src,kind] of [[pageFile,page,ts.ScriptKind.TSX],[utilFile,utility,ts.ScriptKind.TS]]){
  check(ts.createSourceFile(file,src,ts.ScriptTarget.Latest,true,kind).parseDiagnostics.length===0,`${file} parses`);
}
const compiled=ts.transpileModule(utility,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const mod=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(compiled));
const {storageLocationDirectoryFilterParams:filterParams, storageLocationDirectoryShowAllParams:showAllParams}=mod;
check(typeof filterParams==='function' && typeof showAllParams==='function','directory URL helpers present');
const source=new URLSearchParams('location_id=loc1&search=old&zone=Frozen&tab=storage&attention=1');
const afterSearch=filterParams(source,' new name ','Frozen');
check(!afterSearch.has('location_id'),'search clears pinned location');
check(afterSearch.get('search')==='new name','search term normalized');
check(afterSearch.get('zone')==='Frozen','search keeps zone filter');
check(afterSearch.get('tab')==='storage','search preserves unrelated tab');
check(afterSearch.get('attention')==='1','search preserves unrelated attention');
check(source.get('location_id')==='loc1','search never mutates previous params');
const afterZone=filterParams(source,'old','Chilled');
check(!afterZone.has('location_id'),'zone change clears pinned location');
check(afterZone.get('search')==='old','zone change retains search');
check(afterZone.get('zone')==='Chilled','zone changed');
const emptySearch=filterParams(source,'   ','');
check(!emptySearch.has('search'),'blank search removed');
check(!emptySearch.has('zone'),'blank zone removed');
const cleared=showAllParams(source);
for(const field of ['location_id','search','zone'])check(!cleared.has(field),`show-all clears ${field}`);
check(cleared.get('tab')==='storage','show-all preserves route tab');
check(cleared.get('attention')==='1','show-all preserves route attention');
check(source.get('search')==='old','show-all never mutates source');
check(page.includes('const requestedLocation = requestedLocationId ? locations.find('),'selected linked location identified');
check(page.includes('requestedLocationId || search.trim() || zoneFilter.trim()'),'focus treated as active filter');
check(page.includes('onChange={(event) => changeDirectorySearch(event.target.value)}'),'search triggers focus exit');
check(page.includes('onChange={(event) => changeDirectoryZone(event.target.value)}'),'zone triggers focus exit');
check(page.includes('setSearchParams(storageLocationDirectoryFilterParams(searchParams, value, zoneFilter)'),'search URL updated');
check(page.includes('setSearchParams(storageLocationDirectoryFilterParams(searchParams, search, value)'),'zone URL updated');
check(page.includes('setSearchParams(storageLocationDirectoryShowAllParams(searchParams)'),'clear removes focused location');
check(page.includes("? ui('Storage location not found')"),'missing linked location has honest empty state');
check(page.includes('requestedLocation?.name || ui(\'Storage location not found\')'),'focused name and missing status shown');
check(page.includes('disabled={!filtersActive}'),'clear filters enabled while focused');
check(page.includes('new URLSearchParams(searchParams)'),'URL sync preserves unrelated params');
console.log(`PASS ${checks}/${checks} Storage Locations exact-link navigation checks`);
